--
-- 野外BOSS刷新调度表
-- 用于取代所有 AreaBoss...js 事件脚本，实现统一管理和状态持久化
--
CREATE TABLE IF NOT EXISTS `boss_schedule` (
   `id` INT NOT NULL AUTO_INCREMENT COMMENT '自增主键',
   `world` TINYINT NOT NULL COMMENT '世界(大区)ID',
   `channel` TINYINT NOT NULL COMMENT '频道ID',
   `map` INT NOT NULL COMMENT 'BOSS所在的地图ID',
   `mob` INT NOT NULL COMMENT '怪物(BOSS)的ID',
    `nextSpawnTime` BIGINT NOT NULL DEFAULT 0 COMMENT '下一次刷新的精确时间戳(毫秒)',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_boss_schedule_location` (`world`, `channel`, `map`, `mob`) COMMENT '确保每个频道地图的同一个BOSS只有一个调度记录'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='野外BOSS刷新调度表';

